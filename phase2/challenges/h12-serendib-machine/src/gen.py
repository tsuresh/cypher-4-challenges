#!/usr/bin/env python3
"""Generate program.h for the Serendib Machine from the flag.

For each flag byte c[i] the emitted bytecode computes ((in ^ k1[i]) + k2[i]) & 0xff
and CMPs it to a constant t[i] = ((c[i] ^ k1[i]) + k2[i]) & 0xff. k1/k2 are random
per build. The flag is recoverable only by reading the bytecode + inverting.

Usage: gen.py 'CYPHER{...}' > program.h
"""
import sys, os

PUSH, IN, XOR, ADD, CMP, HALT = 0x01, 0x02, 0x03, 0x04, 0x05, 0x06

def main():
    flag = sys.argv[1].encode()
    k1 = os.urandom(len(flag))
    k2 = os.urandom(len(flag))
    prog = bytearray()
    for i, c in enumerate(flag):
        t = ((c ^ k1[i]) + k2[i]) & 0xff
        prog += bytes([IN,
                       PUSH, k1[i], XOR,
                       PUSH, k2[i], ADD,
                       PUSH, t,     CMP])
    prog.append(HALT)

    out = []
    out.append("/* AUTO-GENERATED by gen.py — do not edit. */")
    out.append(f"#define PROG_LEN {len(prog)}")
    out.append(f"#define FLAG_LEN {len(flag)}")
    out.append('__attribute__((section(".vmcode")))')
    out.append("static const unsigned char prog[PROG_LEN] = {")
    for i in range(0, len(prog), 12):
        out.append("  " + ",".join(str(b) for b in prog[i:i+12]) + ",")
    out.append("};")
    print("\n".join(out))

if __name__ == "__main__":
    main()
